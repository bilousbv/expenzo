#!/usr/bin/env node
/**
 * Writes the generated Supabase types to disk as UTF-8.
 *
 * `supabase gen types` only writes to stdout — its `-o` flag is the CLI's
 * global output-format flag, not a file target. A plain shell redirect is not
 * portable either: PowerShell 5.1 writes UTF-16 with a byte-order mark, which
 * TypeScript then refuses to parse. Doing it here keeps Windows and CI
 * identical.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const OUTPUT = 'packages/supabase-types/src/database.types.ts';

// Passed as a single string rather than an args array: the command is static,
// and Node deprecates array arguments combined with `shell: true`. The shell is
// needed at all because the CLI is a `.cmd` shim on Windows.
const result = spawnSync('supabase gen types typescript --local --schema public', {
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
  shell: true,
});

if (result.error) {
  console.error(`Could not run the Supabase CLI: ${result.error.message}`);
  process.exit(1);
}

if (result.status !== 0) {
  console.error(result.stderr?.trim() || 'supabase gen types failed');
  console.error('\nIs the local stack running? Try `pnpm db:start`.');
  process.exit(result.status ?? 1);
}

const banner = [
  '// Generated by `pnpm db:types`. Do not edit by hand.',
  '// Regenerate after every migration; CI asserts this file matches the schema.',
  '',
].join('\n');

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, `${banner}${result.stdout}`, 'utf8');

console.log(`Wrote ${OUTPUT}`);
